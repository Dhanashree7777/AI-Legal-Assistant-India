def generate_pdf(messages):

    pdf = FPDF()
    BASE_DIR = os.path.dirname(os.path.abspath(__file__))

    FONT_PATH = os.path.join(
    BASE_DIR,
    "fonts",
    "DejaVuSans.ttf"
)

    st.pdf.add_font("DejaVu", "", FONT_PATH)

    pdf.add_page()

    pdf.set_auto_page_break(
        auto=True,
        margin=15
    )

    # Header
    pdf.set_font(
        "DejaVu",
        style="B",
        size=16
    )

    pdf.cell(
        0,
        10,
        "AI GENERATED LEGAL INFORMATION REPORT",
        align="C",
        new_x="LMARGIN",
        new_y="NEXT"
    )

    # Date
    pdf.set_font(
        "DejaVu",
        size=10
    )

    pdf.cell(
        0,
        8,
        f"Date Generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        align="C",
        new_x="LMARGIN",
        new_y="NEXT"
    )

    # Jurisdiction
    pdf.cell(
        0,
        8,
        "Jurisdiction: Republic of India",
        align="C",
        new_x="LMARGIN",
        new_y="NEXT"
    )

    pdf.ln(5)

    # Chat history heading
    pdf.set_font(
        "DejaVu",
        style="B",
        size=12
    )

    pdf.cell(
        0,
        10,
        "FULL CASE HISTORY & ANALYSIS:",
        new_x="LMARGIN",
        new_y="NEXT"
    )

    pdf.ln(5)

    # Messages
    for message in messages:

        if message["role"] == "user":
            role_title = "USER (QUERY):"
        else:
            role_title = "AI LEGAL ASSISTANT (ANALYSIS):"

        content = message["content"]

        pdf.set_font(
            "helvetica",
            style="B",
            size=11
        )

        pdf.cell(
            0,
            8,
            role_title,
            new_x="LMARGIN",
            new_y="NEXT"
        )

        pdf.set_font(
            "helvetica",
            size=11
        )

        pdf.multi_cell(0, 8, content)

        pdf.multi_cell(
            0,
            8,
            content
        )

        pdf.ln(5)

    # Disclaimer
    pdf.set_font(
        "helvetica",
        style="I",
        size=9
    )

    pdf.set_text_color(
        100,
        100,
        100
    )

    disclaimer = (
        "Disclaimer: This report is generated by an AI Legal Assistant "
        "and is intended for informational purposes only. "
        "It does not constitute official legal counsel."
    )

    pdf.multi_cell(
        0,
        6,
        disclaimer
    )

    return bytes(pdf.output())


